import uuid
from typing import List, Optional
from backend.app.artifacts.schemas import (
    DashboardSpec,
    MeasureSpec,
    PageSpec,
    RelationshipSpec,
    VisualSpec,
)
from backend.app.artifacts.template_manager import (
    CANONICAL_KPI_MEASURES,
    CANONICAL_RELATIONSHIPS,
)


def build_dashboard_spec(
    title: str,
    business_purpose: str,
    product_scope: str,
    market_scope: str,
    semantic_model_id: Optional[str] = None,
    request_id: Optional[str] = None,
    approval_id: Optional[str] = None,
    kpi_ids: Optional[List[str]] = None,
) -> DashboardSpec:
    spec_id = f"SPEC-{uuid.uuid4().hex[:8].upper()}"

    # Determine measures based on requested KPIs or defaults
    measures: List[MeasureSpec] = []
    if kpi_ids:
        for kid in kpi_ids:
            if kid in CANONICAL_KPI_MEASURES:
                measures.append(CANONICAL_KPI_MEASURES[kid])
    if not measures:
        measures = [
            CANONICAL_KPI_MEASURES["KPI-001"],
            CANONICAL_KPI_MEASURES["KPI-004"],
            CANONICAL_KPI_MEASURES["KPI-027"],
            CANONICAL_KPI_MEASURES["TOTAL_FORECAST"],
        ]

    # If Total Net Sales is present, include Total Forecast support if not already present
    measure_names_set = {m.name for m in measures}
    if "Total Net Sales (M EUR)" in measure_names_set and "Total Forecast (M EUR)" not in measure_names_set:
        if "TOTAL_FORECAST" in CANONICAL_KPI_MEASURES:
            measures.append(CANONICAL_KPI_MEASURES["TOTAL_FORECAST"])
            measure_names_set.add(CANONICAL_KPI_MEASURES["TOTAL_FORECAST"].name)

    # Tables to include
    tables = ["ProductMarketMonthly", "Products", "Markets", "MarketAccess"]

    # Visuals for Page 1
    trend_measures = [m for m in ["Total Net Sales (M EUR)", "Total Forecast (M EUR)"] if m in measure_names_set]
    market_measures = [m for m in ["Total Net Sales (M EUR)"] if m in measure_names_set] or [measures[0].name]

    visuals: List[VisualSpec] = [
        VisualSpec(
            visual_id="card_net_sales",
            title="Total Net Sales",
            visual_type="card",
            table_name="ProductMarketMonthly",
            measures=[m for m in ["Total Net Sales (M EUR)"] if m in measure_names_set] or [measures[0].name],
            position={"x": 20, "y": 20, "width": 280, "height": 140},
        ),
        VisualSpec(
            visual_id="card_variance",
            title="Forecast Variance %",
            visual_type="card",
            table_name="ProductMarketMonthly",
            measures=[m for m in ["Forecast Variance %"] if m in measure_names_set] or [measures[0].name],
            position={"x": 320, "y": 20, "width": 280, "height": 140},
        ),
        VisualSpec(
            visual_id="card_volume",
            title="Units Shipped",
            visual_type="card",
            table_name="ProductMarketMonthly",
            measures=[m for m in ["Total Units Shipped"] if m in measure_names_set] or [measures[0].name],
            position={"x": 620, "y": 20, "width": 280, "height": 140},
        ),
        VisualSpec(
            visual_id="chart_trend",
            title="Monthly Net Sales vs Forecast Trend",
            visual_type="line_chart",
            table_name="ProductMarketMonthly",
            fields=["month"],
            measures=trend_measures,
            position={"x": 20, "y": 180, "width": 700, "height": 480},
        ),
        VisualSpec(
            visual_id="chart_market_sales",
            title="Net Sales by Market",
            visual_type="bar_chart",
            table_name="ProductMarketMonthly",
            fields=["market_id"],
            measures=market_measures,
            position={"x": 740, "y": 180, "width": 500, "height": 480},
        ),
        VisualSpec(
            visual_id="slicer_market",
            title="Select Market",
            visual_type="slicer",
            table_name="Markets",
            fields=["market_id"],
            position={"x": 920, "y": 20, "width": 320, "height": 140},
        ),
    ]

    pages = [
        PageSpec(
            page_id="page_overview",
            page_name="ReportSection_Overview",
            display_name="Commercial Performance Overview",
            visuals=visuals,
        )
    ]

    return DashboardSpec(
        spec_id=spec_id,
        title=title,
        business_purpose=business_purpose,
        product_scope=product_scope,
        market_scope=market_scope,
        semantic_model_id=semantic_model_id,
        request_id=request_id,
        approval_id=approval_id,
        tables=tables,
        measures=measures,
        relationships=CANONICAL_RELATIONSHIPS,
        pages=pages,
        provenance_notes=f"Generated by BIOS Artifact Factory for scope {product_scope} / {market_scope}",
    )
