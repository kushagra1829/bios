"""Write docs/AI/BIOS_1000_QUESTION_BENCHMARK_REPORT.md from the benchmark and results JSON files."""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
bench = json.loads((ROOT / "docs/AI/BIOS_1000_QUESTION_BENCHMARK.json").read_text(encoding="utf-8"))
res = json.loads((ROOT / "docs/AI/BIOS_1000_QUESTION_BENCHMARK_RESULTS.json").read_text(encoding="utf-8"))
s = res["summary"]
names = {q["category"]: q["category_name"] for q in bench["questions"]}
dims = s["by_dimension"]


def dim(key, label):
    d = dims.get(key)
    return f"| {label} | {d['passed']}/{d['total']} | {d['pct']}% |" if d else f"| {label} | not measured | — |"


failed = [r for r in res["results"] if not r["passed"]]
lines = [
    "# BIOS 1,000-Question Benchmark Report",
    "",
    "All data is the synthetic SinceAI 2026 Builder Data Pack; nothing here describes Bayer business performance.",
    "",
    "## Method",
    "",
    f"- **Questions:** {len(bench['questions'])} distinct questions in `docs/AI/BIOS_1000_QUESTION_BENCHMARK.json`, generated by `backend/scripts/generate_ai_benchmark.py` (seed {bench['seed']}).",
    "- **Independent ground truth:** expected values are computed with openpyxl directly from the source workbook. The generator imports no BIOS code.",
    f"- **Execution:** every question was POSTed to the real Assistant API (`{s['base_url']}/api/v1/assistant/requests`) by `backend/scripts/run_ai_benchmark.py`. Provider: deterministic (no LLM), for reproducibility.",
    "- **Scoring:** each response is checked on every dimension that applies to the question; a question passes only if all its checks pass.",
    f"- **Run:** {s['elapsed_s']} s total; mean latency {s['latency_ms']['mean']} ms, p95 {s['latency_ms']['p95']} ms.",
    "",
    "## Overall",
    "",
    f"**{s['fully_passed']} of {s['questions']} questions passed every check ({100 * s['fully_passed'] / s['questions']:.1f}%).**",
    "",
    "## Questions and accuracy by category",
    "",
    "| Category | Name | Questions | Passed | Accuracy |",
    "|---|---|---|---|---|",
]
for cat, v in s["by_category"].items():
    lines.append(f"| {cat} | {names[cat]} | {v['total']} | {v['passed']} | {v['pct']}% |")
lines += ["", "## Ground-truth status", "", "| Status | Questions | Passed |", "|---|---|---|"]
for k, v in s["by_ground_truth"].items():
    lines.append(f"| {k} | {v['total']} | {v['passed']} ({v['pct']}%) |")
lines += [
    "",
    "## Accuracy by dimension",
    "",
    "| Dimension | Passed / applicable | Accuracy |",
    "|---|---|---|",
    dim("intent", "Intent classification"),
    dim("product", "Product resolution"),
    dim("geography", "Geography (exact market set)"),
    dim("date_filter", "Date filter (first/last month)"),
    dim("kpi", "KPI / measure resolution"),
    dim("numeric", "Numerical calculation (±0.01)"),
    dim("coverage", "Record coverage (no duplicate aggregation, no missing records)"),
    dim("data_status", "Data status (answered / partial)"),
    dim("clarification", "Clarification / unsupported / no-data handling"),
    dim("asset_discovery", "Asset discovery"),
    dim("reuse", "Reuse-before-build decision"),
    dim("duplication", "Duplication / consolidation decision"),
    dim("governance_answer", "Governance answers (counts, findings)"),
    dim("migration", "Migration answers (counts per path)"),
    dim("target_governance", "Governance consistency: no unowned/forbidden actionable target"),
    dim("governance_consistency", "Governance consistency: blocked where required"),
    dim("approval_enforced", "Human approval on consequential actions"),
    dim("approval", "Approval flag matches expectation"),
    dim("security", "Prompt-injection flagged"),
    dim("decision_guard", "Forbidden decision avoided"),
    dim("no_unsupported_claim", "No unsupported claim (figures where data is absent)"),
    dim("no_hallucination", "No hallucinated IDs"),
    "",
    f"- **Hallucination rate:** {len(s['hallucinated_ids'])} unknown IDs cited across {s['questions']} responses "
    f"({100 * (1 - dims['no_hallucination']['passed'] / dims['no_hallucination']['total']):.1f}% of responses).",
    f"- **Unsupported-claim rate:** {dims.get('no_unsupported_claim', {}).get('total', 0) - dims.get('no_unsupported_claim', {}).get('passed', 0)} of "
    f"{dims.get('no_unsupported_claim', {}).get('total', 0)} no-data/unsupported questions returned figures.",
    "",
    "## Regression cases",
    "",
    "| # | Question | Decision | Passed |",
    "|---|---|---|---|",
]
for r in s["regression_cases"]:
    lines.append(f"| {r['case']} | {r['question']} | {r['decision']} | {'yes' if r['passed'] else 'NO'} |")
lines += ["", "## Failures", ""]
if failed:
    lines += ["| ID | Category | Question | Failed checks | Got |", "|---|---|---|---|---|"]
    for r in failed:
        bad = ", ".join(k for k, v in r["checks"].items() if not v)
        lines.append(f"| {r['question_id']} | {r['category']} | {r['question']} | {bad} | {r['request_types']} / {r['decision']} |")
else:
    lines.append("None.")
lines += [
    "",
    "## How to read these numbers",
    "",
    "- The benchmark was written by the same workstream that changed BIOS, and BIOS was corrected during development using earlier runs "
    "(first full run: 969/1000). Fixes were generic routing and governance rules, not per-question answers, and no answer is hard-coded. "
    "Even so, these templates share phrasing patterns, so the score is an upper bound for unseen phrasing. Treat it as a regression suite, not proof of general accuracy.",
    "- 216 questions are DATASET_SIGNAL_SUPPORTED and 14 REQUIRES_HUMAN_ADJUDICATION: their expected decision is a defensible set of acceptable actions, not a single verified truth.",
    "- Numerical checks compare against independent workbook sums; every deterministic figure in the benchmark was checked.",
    "- Expected governance counts that depend on the governance engine's own rules (for example RULE-005 audience reach) are checked as lower bounds from raw workbook fields.",
    "- Runs use the deterministic provider. With a local Ollama model, only advisory narrative text and KPI review notes can change; routing, figures, targets and approvals are deterministic and validated after any LLM proposal.",
    "",
]
(ROOT / "docs/AI/BIOS_1000_QUESTION_BENCHMARK_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
print("written", len(lines))
